export function getQuizSourceUrl(source: string): string | undefined {
  const quran = /^Quran (\d+):(\d+(?:–\d+)?)$/.exec(source);
  if (quran) return `https://quran.com/${quran[1]}/${quran[2].replace('–', '-')}`;
  const collections: Record<string, string> = {
    'Sahih al-Bukhari': 'bukhari', 'Sahih Muslim': 'muslim',
    'Sunan Abi Dawud': 'abudawud', 'At-Tirmidhi': 'tirmidhi',
  };
  const hadith = /^(Sahih al-Bukhari|Sahih Muslim|Sunan Abi Dawud|At-Tirmidhi) (\d+[a-z]?)$/.exec(source);
  if (hadith) return `https://sunnah.com/${collections[hadith[1]]}:${hadith[2]}`;
  const introductions: Record<string, string> = {
    'Sunnah.com: Über Hadith': 'about',
    'Sunnah.com: Über Sahih al-Bukhari': 'bukhari/about',
    'Sunnah.com: Über Sahih Muslim': 'muslim/about',
    'An-Nawawi: Vierzig Hadithe, Einleitung': 'nawawi40',
  };
  return introductions[source] ? `https://sunnah.com/${introductions[source]}` : undefined;
}

