import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';

const source = resolve('public/premium-assets/high-res-objects/nur-logo-mosque-3d-v1.webp');
const temporary = await mkdtemp(resolve(tmpdir(), 'nur-brand-'));
try {
  const target = resolve(temporary, 'fallback.webp');
  execFileSync('cwebp', ['-quiet', '-resize', '64', '64', '-q', '55', source, '-o', target]);
  const hash = createHash('sha256').update(await readFile(source)).digest('hex');
  const image = (await readFile(target)).toString('base64');
  await writeFile(resolve('src/shared/brandLogoFallback.ts'), `// Generated by scripts/generate-brand-fallback.mjs from the selected 3D logo.\nexport const BRAND_LOGO_SOURCE_SHA256 = '${hash}';\nexport const BRAND_LOGO_FALLBACK = 'data:image/webp;base64,${image}';\n`);
} finally {
  await rm(temporary, { recursive: true, force: true });
}
